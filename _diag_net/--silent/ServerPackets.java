   private final int _id1;
   private final int _id2;

   private ServerPackets(int id1) {
      this(id1, -1);
   }

   private ServerPackets(int id1, int id2) {
      this._id1 = id1;
      this._id2 = id2;
   }

   public void writeId(ServerPacket packet, WriteBuffer buffer) {
      if (DevelopmentConfig.DEBUG_SERVER_PACKETS) {
         String name = packet.getClass().getSimpleName();
         if (!DevelopmentConfig.EXCLUDED_DEBUG_PACKETS.contains(name)) {
            org.l2jmobius.gameserver.network.PacketLogger.info((this._id2 > 0 ? "[S EX] " : "[S] ") + name);
         }
      }

      buffer.writeByte(this._id1);
      if (this._id2 > 0) {
         buffer.writeShort(this._id2);
      }
   }
